create type public.user_role as enum ('reader', 'editor', 'admin');
create type public.article_status as enum ('draft', 'scheduled', 'published', 'archived');

create table public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  full_name text,
  avatar_url text,
  profile_color text,
  role public.user_role not null default 'reader',
  is_blocked boolean not null default false,
  blocked_reason text,
  is_protected boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  color text,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

create table public.tags (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  slug text not null unique,
  created_at timestamptz not null default now()
);

create table public.articles (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  slug text not null unique,
  subtitle text,
  excerpt text,
  content text not null,
  cover_image_url text,
  category_id uuid references public.categories (id) on delete set null,
  author_id uuid references public.profiles (id) on delete set null,
  status public.article_status not null default 'draft',
  is_featured boolean not null default false,
  is_breaking boolean not null default false,
  reading_time_minutes integer,
  seo_title text,
  seo_description text,
  views_count bigint not null default 0,
  published_at timestamptz,
  scheduled_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint articles_scheduled_needs_date check (status <> 'scheduled' or scheduled_at is not null)
);

create index articles_status_published_idx on public.articles (status, published_at desc);
create index articles_category_idx on public.articles (category_id, published_at desc);
create index articles_author_idx on public.articles (author_id);
create index articles_featured_idx on public.articles (published_at desc) where is_featured;
create index articles_breaking_idx on public.articles (published_at desc) where is_breaking;

create table public.article_tags (
  article_id uuid not null references public.articles (id) on delete cascade,
  tag_id uuid not null references public.tags (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (article_id, tag_id)
);

create index article_tags_tag_idx on public.article_tags (tag_id);

create table public.comments (
  id bigint generated by default as identity primary key,
  article_id uuid not null references public.articles (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  parent_id bigint references public.comments (id) on delete cascade,
  body text not null,
  like_count integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint comments_body_length check (length(trim(body)) between 1 and 2000)
);

create index comments_article_idx on public.comments (article_id, created_at desc);
create index comments_parent_idx on public.comments (parent_id);
create index comments_user_idx on public.comments (user_id, created_at desc);

create table public.comment_likes (
  comment_id bigint not null references public.comments (id) on delete cascade,
  user_id uuid not null references auth.users (id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (comment_id, user_id)
);

create index comment_likes_user_idx on public.comment_likes (user_id);

create table public.newsletter_subscribers (
  id uuid primary key default gen_random_uuid(),
  email text not null,
  confirmed boolean not null default false,
  subscribed_at timestamptz not null default now(),

-- QAP ChacoNews baseline. Every permission here is asserted by supabase/tests/security.sql.

create extension if not exists pg_cron;

-- Helpers live outside the exposed API schema so they can never be called over REST.
create schema if not exists private;
grant usage on schema private to authenticated;

-- New tables and functions start with no access; each one below grants what it needs.
alter default privileges for role postgres in schema public revoke all on tables from anon, authenticated;
alter default privileges for role postgres in schema public revoke all on sequences from anon, authenticated;
alter default privileges for role postgres in schema public revoke execute on functions from public, anon, authenticated;
alter default privileges for role postgres in schema private revoke execute on functions from public;


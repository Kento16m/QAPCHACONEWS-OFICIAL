-- Safe author data for anyone. Runs with the owner's rights on purpose: it exposes only these columns.
create view public.public_profiles with (security_barrier = true) as
  select id, full_name, avatar_url, profile_color from public.profiles;

-- =====================================================
-- Access helpers. A blocked account counts as nobody.
-- =====================================================
create function private.is_active() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles where id = auth.uid() and not is_blocked);
$$;

create function private.is_staff() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role in ('editor', 'admin') and not is_blocked);
$$;

create function private.is_admin() returns boolean
language sql stable security definer set search_path = '' as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin' and not is_blocked);
$$;


  before update of title, slug, subtitle, excerpt, content, cover_image_url, category_id, author_id, status,
    is_featured, is_breaking, reading_time_minutes, seo_title, seo_description, published_at, scheduled_at
  on public.articles
  for each row execute function private.set_updated_at();

create function private.set_article_published_at() returns trigger
language plpgsql set search_path = '' as $$
begin
  if new.status = 'published' and new.published_at is null then
    new.published_at = now();
  end if;
  return new;
end;
$$;

create trigger articles_set_published_at before insert or update of status, published_at on public.articles
  for each row execute function private.set_article_published_at();

create function private.handle_new_user() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, full_name, avatar_url)
  values (
    new.id,
    -- Names are public: fall back to the email's local part, never the whole address.
    left(coalesce(
      nullif(trim(new.raw_user_meta_data ->> 'full_name'), ''),
      nullif(trim(new.raw_user_meta_data ->> 'name'), ''),
      nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''),
      nullif(split_part(new.email, '@', 1), ''),
      'Usuario'
    ), 100),
    coalesce(new.raw_user_meta_data ->> 'avatar_url', new.raw_user_meta_data ->> 'picture')
  );
  return new;
end;
$$;

create trigger on_auth_user_created after insert on auth.users
  for each row execute function private.handle_new_user();

-- Runs with the owner's rights because likers cannot update comments they do not own.
create function private.sync_comment_like_count() returns trigger
language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'INSERT' then
    update public.comments set like_count = like_count + 1 where id = new.comment_id;
    return new;
  end if;
  update public.comments set like_count = greatest(like_count - 1, 0) where id = old.comment_id;
  return old;
end;
$$;

create trigger comment_likes_sync_count after insert or delete on public.comment_likes
  for each row execute function private.sync_comment_like_count();

-- The log records who the database says acted, whatever the browser sent.
create function private.fill_admin_access_log() returns trigger
language plpgsql security definer set search_path = '' as $$
declare
  headers json := nullif(current_setting('request.headers', true), '')::json;
begin
  new.user_id := auth.uid();
  new.email := (select email from auth.users where id = auth.uid());
  select full_name, role::text into new.full_name, new.role from public.profiles where id = auth.uid();
  new.session_id := auth.jwt() ->> 'session_id';
  new.ip_address := coalesce(headers ->> 'cf-connecting-ip', trim(split_part(headers ->> 'x-forwarded-for', ',', 1)));
  new.accessed_at := now();
  return new;
end;
$$;

create trigger admin_access_logs_fill before insert on public.admin_access_logs
  for each row execute function private.fill_admin_access_log();


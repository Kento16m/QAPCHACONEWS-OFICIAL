-- Only the moderate-comment Edge Function may call this, after moderating and verifying the session.
create function public.service_post_comment(p_user_id uuid, p_article_id uuid, p_parent_id bigint, p_body text)
returns public.comments
language plpgsql security definer set search_path = '' as $$
declare
  inserted public.comments;
begin
  -- Serialize per user so simultaneous requests cannot slip past the limit.
  perform pg_advisory_xact_lock(hashtextextended(p_user_id::text, 0));

  if not exists (select 1 from public.profiles where id = p_user_id and not is_blocked) then
    raise exception 'blocked' using errcode = 'QC403';
  end if;

  if not exists (select 1 from public.articles where id = p_article_id and status = 'published' and published_at <= now()) then
    raise exception 'article_not_found' using errcode = 'QC404';
  end if;

  if p_parent_id is not null
    and not exists (select 1 from public.comments where id = p_parent_id and article_id = p_article_id) then
    raise exception 'invalid_parent' using errcode = 'QC400';
  end if;

  if (select count(*) from public.comments where user_id = p_user_id and created_at > now() - interval '1 minute') >= 5 then
    raise exception 'rate_limited' using errcode = 'QC429';
  end if;

  insert into public.comments (article_id, user_id, parent_id, body)
  values (p_article_id, p_user_id, p_parent_id, trim(p_body))
  returning * into inserted;

  return inserted;
end;
$$;

create function public.admin_set_user_role(p_user_id uuid, p_role public.user_role)
returns public.profiles
language plpgsql security definer set search_path = '' as $$
declare
  updated public.profiles;
begin
  if not private.is_admin() or p_user_id = auth.uid() then
    raise exception 'forbidden' using errcode = 'QC403';
  end if;

  update public.profiles set role = p_role where id = p_user_id and not is_protected returning * into updated;

  if updated.id is null then
    raise exception 'forbidden' using errcode = 'QC403';
  end if;

  return updated;
end;
$$;

create function public.admin_set_user_block(p_user_id uuid, p_blocked boolean, p_reason text)
returns public.profiles
language plpgsql security definer set search_path = '' as $$
declare
  updated public.profiles;
begin
  if not private.is_admin() or p_user_id = auth.uid() then
    raise exception 'forbidden' using errcode = 'QC403';
  end if;

  update public.profiles
  set is_blocked = p_blocked, blocked_reason = case when p_blocked then p_reason end
  where id = p_user_id and not is_protected
  returning * into updated;

  if updated.id is null then
    raise exception 'forbidden' using errcode = 'QC403';
  end if;

  -- Ends refresh tokens; a live access token expires within the hour and RLS already rejects it.
  if p_blocked then
    delete from auth.sessions where user_id = p_user_id;
  end if;

  return updated;
end;
$$;

